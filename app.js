  function kusUcusu(a, b) {
    var r = Math.PI / 180, de = (b[0] - a[0]) * r, db = (b[1] - a[1]) * r;
    var h = Math.pow(Math.sin(de / 2), 2) + Math.cos(a[0] * r) * Math.cos(b[0] * r) * Math.pow(Math.sin(db / 2), 2);
    return 2 * 6371 * Math.asin(Math.sqrt(h));
  }
